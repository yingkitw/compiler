// `number[]` and `boolean[]`: literals, indexing, push, and length.
let nums: number[] = [1.0, 2.0, 3.0];
print(nums[0]);
print(nums[1] + nums[2]);

let empty: number[] = [];
empty.push(4.0);
empty.push(5.5);
print(empty[0]);
print(empty.length);

let flags: boolean[] = [true, false];
print(flags[0]);
print(flags[1]);
